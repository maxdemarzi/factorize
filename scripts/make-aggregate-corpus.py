#!/usr/bin/env python3
"""Rewrite the count(*) corpus as one query per aggregate, over the same joins.

    scripts/make-aggregate-corpus.py            # writes tmp/agg_<kind>.psv

The join graphs are the ones the gate was tuned on; only the fold changes. That
is what makes the per-aggregate comparison mean anything: a difference between
kinds is a difference in the fold, not in the queries.

This exists because the previous corpus was generated by hand and not kept, and
65 of its 119 sum(x * y) queries multiplied two INTEGER join keys whose product
overflows INT32. DuckDB raises on those, so more than half the corpus never
produced an answer -- and the gate fired on 30 of the 65 overflowing queries
against 3 of the 54 that worked, which made the published figure for that fold
(0.93x, "slower than not firing") a measurement of how fast each plan reaches
the same error. Recorded as D85; the corpus it was measured on is this one's
reason for existing.

So sum(x * y) casts its first operand to BIGINT. DuckDB then types the product
as BIGINT and computes it at the same width the fold does, which is both the
only form the matcher now accepts (D86) and the only form that answers.
"""

import argparse
import os
import re
import sys

#: The fold each kind applies, given two qualified column names.
KINDS = {
    "min": lambda a, b: f"min({a})",
    "max": lambda a, b: f"max({a})",
    "avg": lambda a, b: f"avg({a})",
    "sum": lambda a, b: f"sum({a})",
    # The cast is load-bearing, not cosmetic -- see the module docstring.
    "sumprod": lambda a, b: f"sum({a}::BIGINT * {b})",
}


def columns_of(predicates, tables):
    """Qualified columns the query already mentions, in predicate order.

    Only join-key columns are available without knowing the schema, and they
    are what the original corpus used. Taking them in predicate order keeps
    the rewrite deterministic.
    """
    seen, out = set(), []
    for predicate in predicates:
        for side in predicate.split("="):
            name = side.strip()
            if re.fullmatch(r"[A-Za-z_][\w]*\.[A-Za-z_][\w]*", name) and name not in seen:
                seen.add(name)
                out.append(name)
    return out


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--list", default="tmp/ce_runnable_sql.psv")
    parser.add_argument("--out-dir", default="tmp")
    parser.add_argument("--kinds", nargs="*", default=sorted(KINDS))
    args = parser.parse_args()

    written = {}
    for kind in args.kinds:
        if kind not in KINDS:
            print(f"unknown kind {kind}", file=sys.stderr)
            return 2
        written[kind] = []

    for raw in open(args.list, errors="replace"):
        fields = raw.rstrip("\n").split("|")
        if len(fields) < 3:
            continue
        name, sql = fields[0], fields[2].strip().rstrip(";")
        lowered = sql.lower()
        try:
            frm, where = lowered.index(" from "), lowered.index(" where ")
        except ValueError:
            continue
        tables = [t.strip() for t in sql[frm + 6 : where].split(",") if t.strip()]
        predicates = [p.strip() for p in re.split(r"\s+and\s+", sql[where + 7 :], flags=re.IGNORECASE)]
        cols = columns_of(predicates, tables)
        if len(cols) < 2:
            continue
        tail = f" FROM {sql[frm + 6: where].strip()} WHERE {' AND '.join(predicates)}"
        for kind in written:
            written[kind].append(f"{name}|0|SELECT {KINDS[kind](cols[0], cols[1])}{tail}")

    os.makedirs(args.out_dir, exist_ok=True)
    for kind, lines in written.items():
        path = os.path.join(args.out_dir, f"agg_{kind}.psv")
        with open(path, "w", newline="\n") as handle:
            handle.write("\n".join(lines) + "\n")
        print(f"{len(lines):>4} queries -> {path}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
